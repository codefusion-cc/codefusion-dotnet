        w.Start(1);
        Assert.Equal("a", await Ok(Run(w, "a")));
        var dropped = await w.Command(new PgStatement("DEALLOCATE ALL")).Run(Keep, new Box());
        Assert.Equal(PgStatus.Broken, dropped.Status);
        Assert.Equal("b", await Ok(Run(w, "b")));
        Assert.Equal(["a", "b"], await Values());
    }

    [Theory(Timeout = 30_000)]
    [InlineData("COMMIT")]
    [InlineData("ROLLBACK")]
    [InlineData("START TRANSACTION")] // SAVEPOINT and RELEASE are refused outside a transaction block: an ordinary error
    public async Task AWriteThatEndsOrSplitsTheGroupsTransactionBreaksTheGroupInsteadOfReplayingOrLosingWrites(string control)
    {
        var w = await NewWriter();
        await Sql($"INSERT INTO {_table} (v) VALUES ('taken')");
        var stmt = new PgStatement(control);
        var a = w.Command(_insert).Text("a").Then(stmt).Run(Keep, new Box()).AsTask();
        var duplicate = Run(w, "taken"); // fails after a's statement ended the transaction it shared with the group
        var b = Run(w, "b");
        w.Start(1);

        // a's statement committed or rolled back the group's writes itself: neither "Ok" nor "failed" is known to be
        // true for the writes before it, and running them again could write them twice
        Assert.Equal(PgStatus.Broken, (await a).Status);
        var (dup, _) = await duplicate;
        Assert.NotEqual(PgStatus.Ok, dup.Status);
        var (rb, vb) = await b;
        string[] values = await Values();
        Assert.Equal(values.Distinct(), values);
        if (rb.IsOk) Assert.Contains(vb!, values);
        Assert.Equal(1, values.Count(v => v == "taken"));
        Assert.Equal("c", await Ok(Run(w, "c")));
    }

    [Fact(Timeout = 60_000)]
    public async Task AFullGroupOfBigWritesWithBigRowsGoesThroughTheSocketsWithoutDeadlock()
    {
        var w = await NewWriter();
        var big = new PgStatement($"INSERT INTO {_table} (v) VALUES ($1) RETURNING v, repeat(v, 4)", PgType.Text);
        var tasks = Enumerable.Range(0, PgWriter.MaxGroup)
            .Select(i => w.Command(big).Text(i + new string('x', 50_000)).Run(static (in PgRow r, object? _) => r.GetBytes(1).Length, null).AsTask()).ToArray();
        w.Start(1);
        var results = await Task.WhenAll(tasks);
        Assert.All(results, r => Assert.True(r.IsOk, r.ToString()));
        Assert.Equal(Enumerable.Range(0, PgWriter.MaxGroup).Select(i => 4L * (i.ToString(System.Globalization.CultureInfo.InvariantCulture).Length + 50_000)), results.Select(r => r.Value));
    }
