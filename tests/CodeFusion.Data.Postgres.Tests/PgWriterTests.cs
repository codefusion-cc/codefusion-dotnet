    [Fact(Timeout = 30_000)]
    public async Task AnArticleWithTagsCommitsAsOneWriteFromTextArraysAndNullableText()
    {
        var w = await NewWriter();
        await Sql($"CREATE TABLE {_table}_d (k bigint, v text)");
        var insert = new PgStatement($"INSERT INTO {_table} (v) VALUES ($1)", PgType.Text);
        var tags = new PgStatement($"INSERT INTO {_table}_d SELECT currval(pg_get_serial_sequence('{_table}', 'id')), t FROM unnest($1::text[]) t", PgType.TextArray);
        var back = new PgStatement(
            $"SELECT a.v, (SELECT string_agg(coalesce(d.v, 'NULL'), ',' ORDER BY d.v NULLS FIRST) FROM {_table}_d d WHERE d.k = a.id), coalesce($1, 'no bio') " +
            $"FROM {_table} a WHERE a.id = currval(pg_get_serial_sequence('{_table}', 'id'))", PgType.Text);
        var rows = new List<string>();
        w.Start(1);
        var res = await w.Command(insert).Text("article"u8).Then(tags).TextArray(["b", null, "ä"]).Then(back).Text((string?)null)
            .Run(static (in PgRow r, object? s) => { ((List<string>)s!).Add($"{r.Text(0)}|{r.Text(1)}|{r.Text(2)}"); return 0; }, rows);
        Assert.True(res.IsOk, res.ToString());
        Assert.Equal(["article|NULL,b,ä|no bio"], rows);

        // an empty array, and elements built one by one from bytes
        var empty = await w.Command(insert).Text("e").Then(tags).BeginTextArray().EndTextArray().Then(back).Text("x")
            .Run(static (in PgRow r, object? s) => { ((List<string>)s!).Add(r.IsNull(1) ? "no tags" : r.Text(1)); return 0; }, rows);
        Assert.True(empty.IsOk, empty.ToString());
        Assert.Equal("no tags", rows[^1]);
        var built = await w.Command(insert).Text("f").Then(tags).BeginTextArray().Element("1"u8).Element("2".AsSpan()).EndTextArray().Then(back).Text("x")
            .Run(static (in PgRow r, object? s) => { ((List<string>)s!).Add(r.Text(1)); return 0; }, rows);
        Assert.True(built.IsOk);
        Assert.Equal("1,2", rows[^1]);
    }

