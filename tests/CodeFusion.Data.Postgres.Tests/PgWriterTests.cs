    [Fact(Timeout = 30_000)]
    public async Task WritesPastTheQueueLimitAreRefusedAtOnceAndTheQueuedOnesCommit()
    {
        var w = await NewWriter();
        var values = Enumerable.Range(0, PgWriter.MaxQueued).Select(i => $"q{i}").ToArray();
        var queued = values.Select(v => Run(w, v)).ToArray();
        var refused = w.Command(_insert).Text("one-too-many").Run(Keep, new Box());

        Assert.True(refused.IsCompletedSuccessfully, "refused without waiting for a loop");
        Assert.Equal(PgStatus.Busy, refused.Result.Status);
        Assert.Equal(PgWriter.MaxQueued, w.Queued);
        w.Start(2);
        Assert.Equal(values, await Task.WhenAll(queued.Select(Ok)));
        Assert.Equal(0, w.Queued);
        Assert.Equal("room-again", await Ok(Run(w, "room-again")));
        Assert.Equal(PgWriter.MaxQueued + 1, (await Values()).Length);
        Assert.DoesNotContain("one-too-many", await Values());
    }

    [Fact(Timeout = 30_000)]
    public async Task AWriteBlockedPastTheLockTimeoutFailsAloneAndItsGroupCommits()
    {
        var timeout = TimeSpan.FromMilliseconds(300);
        var w = await NewWriter(timeout);
        await Sql($"INSERT INTO {_table} (v) VALUES ('locked')");
        await using var holder = await _db!.OpenConnectionAsync();
        await using var tx = await holder.BeginTransactionAsync();
        await using (var lockRow = new NpgsqlCommand($"SELECT v FROM {_table} WHERE v = 'locked' FOR UPDATE", holder, tx))
            await lockRow.ExecuteScalarAsync();

        var blocked = w.Command(new PgStatement($"UPDATE {_table} SET v = 'moved' WHERE v = 'locked' RETURNING v")).Run(Keep, new Box()).AsTask();
        var free = Run(w, "free");
        var sw = Stopwatch.StartNew();
        w.Start(1);

        var b = await blocked;
        Assert.Equal((PgStatus.ServerError, PgErrorCodes.LockNotAvailable), (b.Status, b.SqlState));
        Assert.Equal("free", await Ok(free));
        // one wait for the lock, not the 30 s statement timeout
        Assert.InRange(sw.Elapsed, timeout, TimeSpan.FromSeconds(10));
        await tx.RollbackAsync();
        Assert.Equal(["locked", "free"], await Values());
    }

