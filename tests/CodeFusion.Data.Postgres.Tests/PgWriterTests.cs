    [Fact(Timeout = 30_000)]
    public async Task AWriteWhoseClientLeavesOnceItsGroupRunsStillCommits()
    {
        var w = await NewWriter();
        await Sql($"INSERT INTO {_table} (v) VALUES ('taken')");
        using var leaving = new CancellationTokenSource();
        // the group sleeps first, so the client leaves while it runs; it then fails on "taken", and "stays" runs again
        var sleep = w.Command(new PgStatement("SELECT pg_sleep(0.5)::text")).Run(null, null).AsTask();
        var stays = Run(w, "stays", leaving.Token);
        var failing = Run(w, "taken");
        w.Start(1);
        while (w.Queued > 0) await Task.Delay(5);
        leaving.Cancel();

        Assert.True((await sleep).IsOk);
        var (res, v) = await stays;
        Assert.Equal((PgStatus.Ok, "stays", 2), (res.Status, v, res.Runs));
        await Failed(failing, PgErrorCodes.UniqueViolation);
        Assert.Equal(["taken", "stays"], await Values());
    }

