    /// <summary>
    /// Queues <paramref name="values"/> as one group against existing rows "taken" and "taken2" and checks that the
    /// writes end as if run one by one in order, and how often each good write ran.
    /// </summary>
    async Task<int> MostRunsOfAGoodWrite(string[] values)
    {
        var w = await NewWriter();
        await Sql($"INSERT INTO {_table} (v) VALUES ('taken'), ('taken2')");
        var tasks = values.Select(v => Run(w, v)).ToArray();
        w.Start(1);

        var good = new List<string>();
        int most = 0;
        for (int i = 0; i < values.Length; i++)
        {
            if (values[i].StartsWith("taken", StringComparison.Ordinal) || Array.IndexOf(values, values[i]) < i)
                await Failed(tasks[i], PgErrorCodes.UniqueViolation);
            else
            {
                var (res, v) = await tasks[i];
                Assert.Equal(values[i], v);
                most = Math.Max(most, res.Runs);
                good.Add(values[i]);
            }
        }
        string[] expected = ["taken", "taken2", .. good];
        Assert.Equal(expected, await Values());
        return most;
    }

