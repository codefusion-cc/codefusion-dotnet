    [InlineData("taken,a,x,b,taken2,c,x,d")]
    [InlineData("a,a,a,b")]
    [InlineData("taken,taken2")]
    public async Task AGoodWriteRunsAtMostTwiceWhereverItsGroupFails(string values) =>
        Assert.InRange(await MostRunsOfAGoodWrite(values.Split(',')), 0, 2);

