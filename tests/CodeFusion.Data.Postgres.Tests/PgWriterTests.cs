/// <summary>
/// Group commit against a real Postgres (CODEFUSION_TEST_DB), the scenarios of the contest server's Npgsql writer
/// tests. Each test uses its own table and drops it.
/// </summary>
public sealed class PgWriterTests : IAsyncDisposable
{
    readonly string _table = "pg_writer_" + Guid.NewGuid().ToString("N");
    NpgsqlDataSource? _db;
    PgWriter? _writer;
    PgStatement _insert = null!;

    /// <summary>A writer whose loops are not started yet, so writes queued now share the first group.</summary>
    async Task<PgWriter> NewWriter(TimeSpan? lockTimeout = null)
    {
        Require();
        _db = Admin();
        await Sql($"CREATE TABLE {_table} (id bigserial PRIMARY KEY, v text NOT NULL UNIQUE)");
        _insert = new PgStatement($"INSERT INTO {_table} (v) VALUES ($1) RETURNING v, id", PgType.Text);
        return _writer = new PgWriter(lockTimeout is { } t ? WriterSettings(t) : Settings());
    }

    Task<object?> Sql(string sql) => _db!.Scalar(sql);

    async Task<string[]> Values() =>
        (await Sql($"SELECT coalesce(string_agg(v, ',' ORDER BY id), '') FROM {_table}") as string)!.Split(',', StringSplitOptions.RemoveEmptyEntries);

    /// <summary>The first row's v into the box; the id is the result's value.</summary>
    static readonly PgRowHandler Keep = static (in PgRow r, object? s) =>
    {
        var box = (Box)s!;
        box.Calls++;
        box.Value = r.Text(0);
        return box.Id = r.FieldCount > 1 ? r.GetInt64(1) : 0;
    };

    async Task<(PgResult Result, string? Value)> Run(PgWriter w, string v, CancellationToken aborted = default)
    {
        var box = new Box();
        var res = await w.Command(_insert).Text(v).Run(Keep, box, aborted);
        return (res, box.Value);
    }

    static async Task<string?> Ok(Task<(PgResult Result, string? Value)> t)
    {
        var (res, v) = await t;
        Assert.True(res.IsOk, res.ToString());
        return v;
    }

    static async Task<PgResult> Failed(Task<(PgResult Result, string? Value)> t, string sqlState)
    {
        var (res, v) = await t;
        Assert.Equal(PgStatus.ServerError, res.Status);
        Assert.Equal(sqlState, res.SqlState);
        Assert.Null(v); // a write that didn't commit hands no rows over
        return res;
    }

    public async ValueTask DisposeAsync()
    {
        if (_writer is not null) LoopChecks.Stop(_writer);
        if (_db is null) return;
        await Sql($"DROP TABLE IF EXISTS {_table}, {_table}_d");
        await _db.DisposeAsync();
    }

    [Fact(Timeout = 30_000)]
    public async Task AFailingWriteFailsAloneAndTheRestOfItsGroupCommits()
    {
        var w = await NewWriter();
        await Sql($"INSERT INTO {_table} (v) VALUES ('taken')");
        var tasks = new[] { "a", "b", "taken", "c", "d" }.Select(v => Run(w, v)).ToArray();
        w.Start(1);

        await Failed(tasks[2], PgErrorCodes.UniqueViolation);
        Assert.Equal(["a", "b", "c", "d"], await Task.WhenAll(new[] { tasks[0], tasks[1], tasks[3], tasks[4] }.Select(Ok)));
        Assert.Equal(["taken", "a", "b", "c", "d"], await Values());
        // a and b again without the duplicate, the duplicate alone (its error came from an attempt that rolled back),
        // then c and d
        Assert.Equal(3, w.Counters.Reruns);
    }

    [Fact(Timeout = 30_000)]
    public async Task OfTwoConflictingWritesInOneGroupTheFirstQueuedWins()
    {
        var w = await NewWriter();
        var first = Run(w, "same");
        var second = Run(w, "same");
        w.Start(1);

        Assert.Equal("same", await Ok(first));
        await Failed(second, PgErrorCodes.UniqueViolation);
        Assert.Equal(["same"], await Values());
    }

    [Fact(Timeout = 30_000)]
    public async Task AWriteThatFailedOnlyBecauseOfWhatTheRolledBackAttemptWroteRunsAgainAndCommits()
    {
        var w = await NewWriter();
        await Sql($"CREATE TABLE {_table}_d (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text)");
        var next = new PgStatement($"INSERT INTO {_table}_d (v) VALUES ($1) RETURNING v, id", PgType.Text);
        var one = new PgStatement($"INSERT INTO {_table}_d (id, v) VALUES (1, $1) RETURNING v, id", PgType.Text);
        var (aBox, bBox) = (new Box(), new Box());
        var a = w.Command(next).Text("a").Run(Keep, aBox).AsTask();
        var b = w.Command(one).Text("b").Run(Keep, bBox).AsTask();
        w.Start(1);

        // In the group a took id 1 and b's id 1 collided. The rollback keeps the sequence's step, so a commits with
        // id 2 on its own, and id 1 is free: b's error came from a write that never committed
        Assert.True((await a).IsOk);
        var rb = await b;
        Assert.True(rb.IsOk, rb.ToString());
        Assert.Equal((2L, 1L), (aBox.Id, bBox.Id));
        Assert.Equal("a,b", await Sql($"SELECT string_agg(v, ',' ORDER BY id DESC) FROM {_table}_d"));
    }

    [Fact(Timeout = 30_000)]
    public async Task SeveralFailuresInOneGroupEachFailAlone()
    {
        var w = await NewWriter();
        await Sql($"INSERT INTO {_table} (v) VALUES ('x'), ('y')");
        string[] values = ["x", "a", "y", "b", "x", "c"];
