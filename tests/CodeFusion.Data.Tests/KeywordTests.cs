using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using System.Threading.Tasks;
using CodeFusion.Data.Generator;
using Npgsql;
using Xunit;

namespace CodeFusion.Data.Tests;

/// <summary>
/// Every word Postgres reserves (pg_get_keywords' R, reserved, and T, reserved but allowed as a function or type
/// name), as a lambda's name and as a column's: each statement the generator writes for them prepares in Postgres.
/// The list is the server's own, so a word a later Postgres reserves fails here.
/// </summary>
public sealed class KeywordTests
{
    static async Task<List<string>> ReservedWords(NpgsqlDataSource db)
    {
        var words = new List<string>();
        await using var cmd = db.CreateCommand("SELECT word FROM pg_get_keywords() WHERE catcode IN ('R', 'T') ORDER BY word");
        await using var r = await cmd.ExecuteReaderAsync();
        while (await r.ReadAsync()) words.Add(r.GetString(0));
        return words;
    }

    [Fact]
    public async Task EveryReservedWordIsQuotedAsAColumn()
    {
        TestDb.Require();
        await using var admin = TestDb.Admin();
        var words = await ReservedWords(admin);
        Assert.True(words.Count > 90, string.Join(",", words));
        var dialect = new Dialect();
        Assert.DoesNotContain(words, w => dialect.Quote(w) != "\"" + w + "\"");
    }

    [Fact]
    public async Task EveryReservedWordAsALambdasNameAndAColumnsPrepares()
    {
        TestDb.Require();
        await using var admin = TestDb.Admin();
        var words = await ReservedWords(admin);
        var props = new StringBuilder();
        var methods = new StringBuilder();
        var table = new StringBuilder("CREATE TABLE kw_rows (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
        var names = new List<string>();
        for (int i = 0; i < words.Count; i++)
        {
            string w = words[i], x = "@" + w;
            props.Append(CultureInfo.InvariantCulture, $"    [Column(\"{w}\")] public long P{i} {{ get; init; }}\n");
            table.Append(CultureInfo.InvariantCulture, $", \"{w}\" bigint");
            methods.Append(CultureInfo.InvariantCulture, $"""
                    public Many<long> Sel{i}(long v) => Rows.Where({x} => {x}.P{i} > v).OrderBy({x} => {x}.P{i}).Select({x} => {x}.P{i}).Many();
                    public Write Ins{i}(long v) => Insert(Rows, new KwRow {"{"} P{i} = v {"}"});
                    public Write<long> Ret{i}(long v) => Insert(Rows, new KwRow {"{"} P{i} = v {"}"}).Select({x} => {x}.P{i});
                    public Write Upd{i}(long v) => Rows.Where({x} => {x}.Id == v).Update({x} => new KwRow {"{"} P{i} = {x}.P{i} + v {"}"});
                    public One<long> Del{i}(long v) => Rows.Where({x} => {x}.Id == v).DeleteIf({x} => {x}.P{i} == v).Select({x} => {x}.P{i}).One();
                    public Write<long> UpdIf{i}(long v) => Rows.Where({x} => {x}.Id == v).UpdateIf({x} => {x}.P{i} == v, {x} => new KwRow {"{"} P{i} = v {"}"}).Select({x} => {x}.P{i});

                """);
            names.AddRange(new[] { "Sel", "Ins", "Ret", "Upd", "Del", "UpdIf" }.Select(n => n + i.ToString(CultureInfo.InvariantCulture)));
        }
        string source = $$"""
            [Table("kw_rows")]
            public sealed class KwRow
            {
                public long Id { get; init; }
            {{props}}
            }
            public sealed partial class Db : DataContext<Postgres>
            {
                public Table<KwRow> Rows => Table<KwRow>();
            {{methods}}
            }
            """;
        var result = GeneratorHarness.Run(source);
        Assert.True(result.Generator.IsEmpty && result.Errors.IsEmpty, string.Join("\n", result.Generator.Concat(result.Errors).Take(10)));

        await admin.Execute($"DROP SCHEMA IF EXISTS cfdata_kw CASCADE; CREATE SCHEMA cfdata_kw; SET search_path = cfdata_kw; {table})");
        await using var db = TestDb.Admin("cfdata_kw");
        await using var conn = await db.OpenConnectionAsync();
        var failures = new List<string>();
        foreach (var name in names)
        {
            string sql = result.Sql(name);
            try
            {
                await using var prepare = new NpgsqlCommand($"PREPARE s AS {sql}", conn);
                await prepare.ExecuteNonQueryAsync();
                await using var deallocate = new NpgsqlCommand("DEALLOCATE s", conn);
                await deallocate.ExecuteNonQueryAsync();
            }
            catch (PostgresException e)
            {
                failures.Add($"{name}: {e.MessageText}\n  {sql}");
            }
        }
        Assert.True(failures.Count == 0, $"{failures.Count} of {names.Count} statements don't prepare:\n" + string.Join("\n", failures.Take(12)));
    }
}
