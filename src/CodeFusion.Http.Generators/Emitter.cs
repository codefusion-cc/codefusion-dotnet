using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace CodeFusion.Http.Generators;

/// <summary>Writes the generated source: one file of endpoints, and one per bound struct.</summary>
internal static class Emitter
{
    const string Http = "global::CodeFusion.Http";
    const string Header = "// <auto-generated/> by the CodeFusion.Http endpoint generator\n#nullable enable\n";

    sealed class Writer
    {
        readonly StringBuilder _sb = new();
        int _indent;

        public Writer Line(string text = "")
        {
            if (text.Length > 0) _sb.Append(' ', 4 * _indent).Append(text);
            _sb.Append('\n');
            return this;
        }

        public Writer Open(string text)
        {
            if (text.Length > 0) Line(text);
            Line("{");
            _indent++;
            return this;
        }

        public Writer Close(string suffix = "")
        {
            _indent--;
            return Line("}" + suffix);
        }

        public override string ToString() => _sb.ToString();
    }

    // ---- Endpoints ----

    public static string Endpoints(IReadOnlyList<EndpointModel> endpoints)
    {
        var w = new Writer();
        w.Line(Header.TrimEnd('\n'));
        w.Open("namespace System.Runtime.CompilerServices");
        w.Line("[global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = true)]");
        w.Line("file sealed class InterceptsLocationAttribute(int version, string data) : global::System.Attribute");
        w.Open("");
        w.Line("public int Version { get; } = version;");
        w.Line("public string Data { get; } = data;");
        w.Close();
        w.Close();
        w.Line();
        w.Open("namespace CodeFusion.Http.Generated");

        // Interceptors: each Map call becomes the registration of its compiled endpoint.
        w.Open("file static class Interceptors");
        for (int i = 0; i < endpoints.Count; i++)
        {
            EndpointModel e = endpoints[i];
            if (i > 0) w.Line();
            w.Line($"// {e.Display}");
            w.Line($"[global::System.Runtime.CompilerServices.InterceptsLocation({e.Version}, \"{e.Data}\")]");
            w.Line($"public static {Http}.EndpointBuilder Map{i}(this {Http}.IEndpointRouteBuilder routes, string pattern, {e.DelegateParameterType} handler) =>");
            string make = e.DirectCall is not null ? $"new Endpoint{i}()"
                : e.HandlerDelegateType == e.DelegateParameterType ? $"new Endpoint{i}(handler)"
                : $"new Endpoint{i}(({e.HandlerDelegateType})handler)";
            w.Line($"    routes.Map({Http}.RequestMethod.{e.Method}, pattern, {make});");
        }
        w.Close();

        // One sender per reply type.
        var senders = new Dictionary<string, int>(StringComparer.Ordinal);
        foreach (EndpointModel e in endpoints)
            if (!senders.ContainsKey(e.Reply.Type)) senders[e.Reply.Type] = senders.Count;

        for (int i = 0; i < endpoints.Count; i++)
        {
            w.Line();
            Endpoint(w, endpoints[i], i, senders[endpoints[i].Reply.Type]);
        }

        foreach (var pair in senders)
        {
            ReplyModel r = endpoints.First(e => e.Reply.Type == pair.Key).Reply;
            w.Line();
            Sender(w, r, pair.Value);
        }
        if (endpoints.Any(e => e.Reply.Kind is ReplyKind.Self or ReplyKind.Nested))
        {
            w.Line();
            w.Open("file static class Replies");
            w.Line("// through the interface, so a reply implementing it explicitly is written too: a struct's call is constrained, not boxed");
            w.Line($"public static global::System.Threading.Tasks.ValueTask Write<T>(T reply, {Http}.RequestContext c) where T : global::CodeFusion.IReply => reply.WriteAsync(c);");
            w.Close();
        }

        var objects = new Dictionary<string, ObjectShape>(StringComparer.Ordinal);
        foreach (EndpointModel e in endpoints)
            foreach (ObjectShape o in e.Objects)
                objects[o.Type] = o;
        var replies = endpoints.Where(e => e.Reply.Kind == ReplyKind.Json).Select(e => e.Reply)
            .GroupBy(r => r.ValueType!, StringComparer.Ordinal).Select(g => g.First()).OrderBy(r => r.ValueType, StringComparer.Ordinal).ToList();
        if (replies.Count > 0)
        {
            w.Line();
            Json(w, replies, objects.Values.OrderBy(o => o.Type, StringComparer.Ordinal).ToList());
        }
        w.Close();
        return w.ToString();
    }

    static void Endpoint(Writer w, EndpointModel e, int i, int sender)
    {
        w.Open($"file sealed class Endpoint{i} : {Http}.Endpoint");
        var fields = new List<string>();
        if (e.DirectCall is null) fields.Add($"readonly {e.HandlerDelegateType} _handler;");
        for (int p = 0; p < e.Parameters.Count; p++)
        {
            ParameterModel pm = e.Parameters[p];
            switch (pm.Kind)
            {
                case ParameterKind.RouteText or ParameterKind.RouteInt64 or ParameterKind.RouteInt32: fields.Add($"int _route{p};"); break;
                case ParameterKind.Service: fields.Add($"{pm.Type} _service{p} = null!;"); break;
                case ParameterKind.ScopedService: fields.Add($"{pm.Type}? _service{p};"); fields.Add($"int _slot{p};"); break;
            }
        }
        foreach (string f in fields) w.Line(f);
        if (fields.Count > 0) w.Line();
        if (e.DirectCall is null)
        {
            w.Line($"public Endpoint{i}({e.HandlerDelegateType} handler) => _handler = handler;");
            w.Line();
        }

        w.Open($"public override void Initialize({Http}.EndpointSetup setup)");
        for (int p = 0; p < e.Parameters.Count; p++)
        {
            ParameterModel pm = e.Parameters[p];
            switch (pm.Kind)
            {
                case ParameterKind.RouteText or ParameterKind.RouteInt64 or ParameterKind.RouteInt32:
                    w.Line($"_route{p} = setup.RouteValue({Literal(pm.Name)});");
                    break;
                case ParameterKind.Service:
                    w.Line($"_service{p} = setup.Singleton<{pm.Type}>();");
                    break;
                case ParameterKind.ScopedService:
                    w.Line($"_service{p} = setup.Service<{pm.Type}>(out _slot{p});");
                    break;
                case ParameterKind.Viewer:
                    w.Line("setup.UsesViewer();");
                    break;
            }
        }
        w.Close();
        w.Line();

        w.Open($"public override global::System.Threading.Tasks.ValueTask Invoke({Http}.RequestContext c)");
        // Binding order: route values, then the query, then the body; the dispatcher checked auth already.
        for (int p = 0; p < e.Parameters.Count; p++)
        {
            ParameterModel pm = e.Parameters[p];
            switch (pm.Kind)
            {
                case ParameterKind.RouteText:
                    w.Line($"{pm.Type} p{p} = c.RouteText(_route{p});");
                    break;
                case ParameterKind.RouteInt64:
                    w.Line($"if (!c.TryRouteInt64(_route{p}, out long p{p}){Outside(pm, $"p{p}")}) return c.RejectRouteValue(this);");
                    break;
                case ParameterKind.RouteInt32:
                    w.Line($"if (!c.TryRouteInt32(_route{p}, out int p{p}){Outside(pm, $"p{p}")}) return c.RejectRouteValue(this);");
                    break;
            }
        }
        for (int p = 0; p < e.Parameters.Count; p++)
            if (e.Parameters[p].Kind == ParameterKind.Query)
                w.Line($"if ({e.Parameters[p].Type}.__BindQuery(c.Query, out {e.Parameters[p].Type} p{p}) is {{ }} e{p}) return e{p}.WriteAsync(c);");
        for (int p = 0; p < e.Parameters.Count; p++)
            if (e.Parameters[p].Kind == ParameterKind.Body)
                w.Line($"if ({e.Parameters[p].Type}.__BindBody(c.RequestBody, out {e.Parameters[p].Type} p{p}) is {{ }} e{p}) return e{p}.WriteAsync(c);");
        var args = new List<string>();
        for (int p = 0; p < e.Parameters.Count; p++)
        {
            ParameterModel pm = e.Parameters[p];
            switch (pm.Kind)
            {
                case ParameterKind.Viewer: args.Add("c.Viewer"); break;
                case ParameterKind.Service: args.Add($"_service{p}"); break;
                case ParameterKind.ScopedService: args.Add($"_slot{p} < 0 ? _service{p}! : c.Scoped<{pm.Type}>(_slot{p})"); break;
                case ParameterKind.Response: args.Add("c"); break;
                case ParameterKind.Exchange: args.Add("c.Exchange"); break;
                case ParameterKind.Aborted: args.Add("c.Aborted"); break;
                default: args.Add($"p{p}"); break;
            }
        }
        string call = $"{e.DirectCall ?? "_handler"}({string.Join(", ", args)})";
        w.Line(e.Reply.Async ? $"return c.Await<{e.Reply.Type}, Send{sender}>({call});" : $"return Send{sender}.Send({call}, c);");
        w.Close();
        w.Close();
    }

    /// <summary>" || " and the condition that a route value is outside its [Range], or nothing when it has none.</summary>
    static string Outside(ParameterModel pm, string value) =>
        (pm.Min is null ? "" : $" || {value} < {pm.Min}") + (pm.Max is null ? "" : $" || {value} > {pm.Max}");

    static void Sender(Writer w, ReplyModel r, int i)
    {
        w.Open($"file struct Send{i} : {Http}.IReplySender<{r.Type}>");
        w.Open($"public static global::System.Threading.Tasks.ValueTask Send({r.Type} reply, {Http}.RequestContext c)");
        switch (r.Kind)
        {
            case ReplyKind.Self:
                w.Line("return Replies.Write(reply, c);");
                break;
            case ReplyKind.Error:
                w.Line("return reply.WriteAsync(c);");
                break;
            case ReplyKind.Nested:
                w.Line("if (!reply.HasValue) return reply.WithoutValue.WriteAsync(c);");
                w.Line("c.Status = reply.Status;");
                w.Line("return Replies.Write(reply.Value, c);");
                break;
            case ReplyKind.Json:
                w.Line("if (!reply.HasValue) return reply.WithoutValue.WriteAsync(c);");
                w.Line("c.Status = reply.Status;");
                w.Line($"Json.{ReplyWriter(r.ValueType!)}(c.Json, reply.Value);");
                w.Line("return default;");
                break;
        }
        w.Close();
        w.Close();
    }

    // ---- JSON ----

    static string Id(string type)
    {
        var sb = new StringBuilder();
        foreach (char ch in type.Replace("global::", ""))
            sb.Append(char.IsLetterOrDigit(ch) ? ch : '_');
        return sb.ToString();
    }

    static string ObjectWriter(string type) => "Write_" + Id(type);
    static string ReplyWriter(string type) => "Reply_" + Id(type);

    static void Json(Writer w, List<ReplyModel> replies, List<ObjectShape> objects)
    {
        var names = new Dictionary<string, string>(StringComparer.Ordinal);
        string Name(string json)
        {
            if (!names.TryGetValue(json, out string? n)) names[json] = n = "N" + names.Count.ToString(CultureInfo.InvariantCulture);
            return n;
        }
        foreach (ReplyModel r in replies)
            if (r.Envelope is not null) Name(r.Envelope);
        foreach (ObjectShape o in objects)
            foreach (MemberShape m in o.Members)
                Name(m.JsonName);

        w.Open("file static class Json");
        foreach (var pair in names)
            w.Line($"static readonly global::System.Text.Json.JsonEncodedText {pair.Value} = global::System.Text.Json.JsonEncodedText.Encode({Literal(pair.Key)}, global::System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping);");

        foreach (ReplyModel r in replies)
        {
            w.Line();
            w.Open($"public static void {ReplyWriter(r.ValueType!)}(global::System.Text.Json.Utf8JsonWriter w, {r.ValueType} value)");
            if (r.Envelope is not null)
            {
                w.Line("w.WriteStartObject();");
                w.Line($"w.WritePropertyName({Name(r.Envelope)});");
            }
            int temp = 0;
            WriteValue(w, r.Value!, "value", null, ref temp);
            if (r.Envelope is not null) w.Line("w.WriteEndObject();");
            w.Close();
        }

        foreach (ObjectShape o in objects)
        {
            w.Line();
            w.Open($"public static void {ObjectWriter(o.Type)}(global::System.Text.Json.Utf8JsonWriter w, {(o.IsClass ? "" : "in ")}{o.Type} value)");
            w.Line("w.WriteStartObject();");
            int temp = 0;
            foreach (MemberShape m in o.Members) WriteValue(w, m.Value, "value." + Analysis.Identifier(m.Member), Name(m.JsonName), ref temp);
            w.Line("w.WriteEndObject();");
            w.Close();
        }

        w.Line();
        w.Open("static void Raw(global::System.Text.Json.Utf8JsonWriter w, global::CodeFusion.RawJson json)");
        w.Line("if (json.Text.IsEmpty) w.WriteNullValue();");
        w.Line("else w.WriteRawValue(json.Span, skipInputValidation: true);");
        w.Close();
        w.Line();
        w.Open("static void Time(global::System.Text.Json.Utf8JsonWriter w, global::CodeFusion.Timestamp time)");
        w.Line("global::System.Span<byte> text = stackalloc byte[global::CodeFusion.Timestamp.FormattedLength];");
        w.Line("if (!time.TryFormat(text, out int n)) throw new global::System.ArgumentOutOfRangeException(nameof(time), \"a timestamp outside years 1 to 9999\");");
        w.Line("w.WriteStringValue(text[..n]);");
        w.Close();
        w.Line();
        w.Open("static void Texts(global::System.Text.Json.Utf8JsonWriter w, global::CodeFusion.Utf8List list)");
        w.Line("w.WriteStartArray();");
        w.Line("foreach (global::CodeFusion.Utf8 text in list) w.WriteStringValue(text.Span);");
        w.Line("w.WriteEndArray();");
        w.Close();
        w.Close();
    }

    /// <summary>Writes <paramref name="expr"/>, as the property <paramref name="name"/> (a JsonEncodedText field) or,
    /// when it is null, as a value.</summary>
    static void WriteValue(Writer w, ValueShape v, string expr, string? name, ref int temp)
    {
        if (v.Nullable)
        {
            string x = "v" + temp++.ToString(CultureInfo.InvariantCulture);
            w.Line($"if ({expr} is {{ }} {x})");
            w.Open("");
            WriteValue(w, v with { Nullable = false }, x, name, ref temp);
            w.Close();
            w.Line(name is null ? "else w.WriteNullValue();" : $"else w.WriteNull({name});");
            return;
        }
        string prop = name is null ? "" : name + ", ";
        switch (v.Kind)
        {
            case ValueKind.Utf8:
                w.Line(name is null ? $"w.WriteStringValue({expr}.Span);" : $"w.WriteString({name}, {expr}.Span);");
                return;
            case ValueKind.String:
                w.Line(name is null ? $"w.WriteStringValue({expr});" : $"w.WriteString({name}, {expr});");
                return;
            case ValueKind.Bool:
                w.Line(name is null ? $"w.WriteBooleanValue({expr});" : $"w.WriteBoolean({name}, {expr});");
                return;
            case ValueKind.Number or ValueKind.Enum:
                string n = v.Cast is null ? expr : $"({v.Cast}){expr}";
                w.Line(name is null ? $"w.WriteNumberValue({n});" : $"w.WriteNumber({prop}{n});");
                return;
        }
        if (name is not null) w.Line($"w.WritePropertyName({name});");
        switch (v.Kind)
        {
            case ValueKind.RawJson:
                w.Line($"Raw(w, {expr});");
                break;
            case ValueKind.Timestamp:
                w.Line($"Time(w, {expr});");
                break;
            case ValueKind.Utf8List:
                w.Line($"Texts(w, {expr});");
                break;
            case ValueKind.Object:
                w.Line($"{ObjectWriter(v.ObjectType!)}(w, {expr});");
                break;
            case ValueKind.Sequence:
                string e = "e" + temp++.ToString(CultureInfo.InvariantCulture);
                w.Line("w.WriteStartArray();");
                w.Line($"foreach (var {e} in {expr})");
                w.Open("");
                WriteValue(w, v.Element!, e, null, ref temp);
                w.Close();
                w.Line("w.WriteEndArray();");
                break;
        }
    }

    // ---- Binders ----

    static void OpenHome(Writer w, TypeHome home)
    {
        w.Line(Header.TrimEnd('\n'));
        if (home.Namespace is not null)
        {
            w.Line($"namespace {home.Namespace};");
            w.Line();
        }
        foreach (string c in home.Containers) w.Open(c);
        w.Open($"partial {home.Keyword} {home.Name}");
    }

    static void CloseHome(Writer w, TypeHome home)
    {
        w.Close();
        foreach (string _ in home.Containers) w.Close();
    }

    public static string Query(QueryModel q)
    {
        var w = new Writer();
        OpenHome(w, q.Home);
        w.Line("/// <summary>Binds the query string; null, or the reply to a number that isn't valid. Written by the CodeFusion.Http generator.</summary>");
        w.Line("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        w.Open($"internal static global::CodeFusion.ErrorReply? __BindQuery(in {Http}.QuerySource query, out {q.Home.FullName} value)");
        w.Line("value = default;");
        var assigns = new List<string>();
        for (int i = 0; i < q.Fields.Count; i++)
        {
            QueryField f = q.Fields[i];
            string key = Utf8Literal(f.Key);
            if (f.Kind == QueryFieldKind.Text)
            {
                if (f.Nullable)
                {
                    w.Line($"global::CodeFusion.Utf8? f{i} = query.TryText({key}, out global::CodeFusion.Utf8 t{i}) ? t{i} : null;");
                }
                else w.Line($"query.TryText({key}, out global::CodeFusion.Utf8 f{i});");
                assigns.Add($"{Analysis.Identifier(f.Member)} = f{i}");
                continue;
            }
            string type = f.Kind == QueryFieldKind.Int32 ? "int" : "long";
            string absent = f.Default is not null ? (f.Kind == QueryFieldKind.Int32 ? $"(int){f.Default}" : f.Default) : f.Nullable ? "null" : "0";
            w.Line($"{type}{(f.Nullable ? "?" : "")} f{i};");
            w.Line($"switch (query.TryNumber({key}, {f.Min}, {f.Max}, out long n{i}))");
            w.Open("");
            w.Line($"case {Http}.QueryNumber.Valid: f{i} = {(f.Kind == QueryFieldKind.Int32 ? $"(int)n{i}" : $"n{i}")}; break;");
            w.Line($"case {Http}.QueryNumber.Absent: f{i} = {absent}; break;");
            w.Line($"default: return {q.Invalid};");
            w.Close();
            assigns.Add($"{Analysis.Identifier(f.Member)} = f{i}");
        }
        w.Line(assigns.Count == 0 ? "value = new();" : $"value = new() {{ {string.Join(", ", assigns)} }};");
        w.Line("return null;");
        w.Close();
        CloseHome(w, q.Home);
        return w.ToString();
    }

    public static string Body(BodyModel b)
    {
        var w = new Writer();
        OpenHome(w, b.Home);
        int buffer = 6 * Math.Max(1, b.Fields.Select(f => Encoding.UTF8.GetByteCount(f.JsonName)).Concat([b.Envelope is null ? 0 : Encoding.UTF8.GetByteCount(b.Envelope)]).Max());
        string structural = b.InvalidBody ?? "source.InvalidBody";
        string fieldError = b.Invalid ?? "source.InvalidBody";

        w.Line("/// <summary>Binds the request body; null, or the reply to a body that isn't valid. Written by the CodeFusion.Http generator.</summary>");
        w.Line("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        w.Open($"internal static global::CodeFusion.ErrorReply? __BindBody(in {Http}.BodySource source, out {b.Home.FullName} value)");
        w.Line("value = default;");
        w.Line($"if (source.IsEmpty) return source.MissingBody ?? source.MalformedBody ?? {structural};");
        w.Line($"var b = new {Http}.JsonBody(source);");
        w.Line($"global::System.Span<byte> name = stackalloc byte[{buffer}];");
        Locals(w, b);
        if (b.Envelope is not null) w.Line("bool found = false;");
        w.Line("try");
        w.Open("");
        w.Line("// a root that isn't an object: JSON of another shape, or malformed further on, which the check tells without throwing");
        w.Line("if (!b.ReadRootObject())");
        w.Line($"    return b.IsWellFormed() ? {structural} : source.MalformedBody ?? {structural};");
        if (b.Envelope is not null)
        {
            w.Line("while (b.NextProperty())");
            w.Open("");
            w.Line($"if (!global::System.MemoryExtensions.SequenceEqual(b.PropertyName(name), {Utf8Literal(b.Envelope)}))");
            w.Open("");
            w.Line("b.SkipValue();");
            w.Line("continue;");
            w.Close();
            w.Line("// a later wrapper replaces an earlier one, fields and all");
            for (int i = 0; i < b.Fields.Count; i++) w.Line($"f{i} = default;");
            w.Line("found = b.ReadObject();");
            w.Line("if (!found) continue;");
            ReadFields(w, b);
            w.Close();
        }
        else ReadFields(w, b);
        w.Line("b.ReadToEnd();");
        w.Close();
        w.Line("catch (global::System.Text.Json.JsonException)");
        w.Open("");
        w.Line($"return source.MalformedBody ?? {structural};");
        w.Close();
        if (b.Envelope is not null) w.Line($"if (!found) return {structural};");
        Validate(w, b, i => b.Fields[i].Error ?? fieldError, nested: false);
        w.Line("return null;");
        w.Close();

        w.Line();
        w.Line("/// <summary>Reads this struct as a nested object of a request body. Written by the CodeFusion.Http generator.</summary>");
        w.Line("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        w.Open($"internal static {Http}.BodyValue __ReadNested(ref {Http}.JsonBody b, out {b.Home.FullName} value, out global::CodeFusion.ErrorReply? error)");
        w.Line("value = default;");
        w.Line("error = null;");
        w.Line($"{Http}.BodyKind kind = b.ReadNested();");
        w.Line($"if (kind != {Http}.BodyKind.Nested) return kind == {Http}.BodyKind.Missing ? default : {Http}.BodyValue.FromNested(false);");
        w.Line($"global::System.Span<byte> name = stackalloc byte[{buffer}];");
        Locals(w, b);
        ReadFields(w, b);
        Validate(w, b, i => b.Fields[i].Error ?? b.Invalid, nested: true);
        w.Line($"return {Http}.BodyValue.FromNested(true);");
        w.Close();

        CloseHome(w, b.Home);
        return w.ToString();
    }

    static void Locals(Writer w, BodyModel b)
    {
        for (int i = 0; i < b.Fields.Count; i++)
        {
            BodyField f = b.Fields[i];
            w.Line($"{Http}.BodyValue f{i} = default;");
            if (f.Kind == BodyFieldKind.Nested)
            {
                w.Line($"{f.NestedType} n{i} = default;");
                w.Line($"global::CodeFusion.ErrorReply? e{i} = null;");
            }
        }
    }

    static void ReadFields(Writer w, BodyModel b)
    {
        w.Line("while (b.NextProperty())");
        w.Open("");
        if (b.Fields.Count == 0)
        {
            w.Line("b.SkipValue();");
            w.Close();
            return;
        }
        w.Line("global::System.ReadOnlySpan<byte> n = b.PropertyName(name);");
        for (int i = 0; i < b.Fields.Count; i++)
        {
            BodyField f = b.Fields[i];
            string read = f.Kind switch
            {
                BodyFieldKind.Text => "b.ReadText()",
                BodyFieldKind.TextList => "b.ReadTextArray()",
                BodyFieldKind.Int64 => "b.ReadInt64()",
                BodyFieldKind.Int32 => "b.ReadInt32()",
                BodyFieldKind.Double => "b.ReadDouble()",
                BodyFieldKind.Bool => "b.ReadBoolean()",
                _ => $"{f.NestedType}.__ReadNested(ref b, out n{i}, out e{i})",
            };
            w.Line($"{(i == 0 ? "if" : "else if")} (global::System.MemoryExtensions.SequenceEqual(n, {Utf8Literal(f.JsonName)})) f{i} = {read};");
        }
        w.Line("else b.SkipValue();");
        w.Close();
    }

    /// <summary>Checks each field in declaration order and sets the value; a field's error is
    /// <paramref name="error"/>(i), which in a nested struct may be null (the outer field's reply then answers).</summary>
    static void Validate(Writer w, BodyModel b, Func<int, string?> error, bool nested)
    {
        string Fail(int i, string? specific = null)
        {
            string? e = specific is null ? error(i) : error(i) is { } own ? $"{specific} ?? {own}" : specific;
            if (!nested) return $"return {e};";
            return e is null ? $"return {Http}.BodyValue.FromNested(false);" : $"{{ error = {e}; return {Http}.BodyValue.FromNested(false); }}";
        }
        var assigns = new List<string>();
        for (int i = 0; i < b.Fields.Count; i++)
        {
            BodyField f = b.Fields[i];
            string fi = $"f{i}";
            switch (f.Kind)
            {
                case BodyFieldKind.Text when !f.Nullable:
                    w.Line($"if (!{fi}.IsRequiredText) {Fail(i)}");
                    assigns.Add($"{Analysis.Identifier(f.Member)} = b.Text({fi})");
                    break;
                case BodyFieldKind.Text:
                    w.Line($"if (!{fi}.IsOptionalText({(f.NonEmpty ? "true" : "false")})) {Fail(i)}");
                    assigns.Add($"{Analysis.Identifier(f.Member)} = {fi}.IsMissing ? null : b.Text({fi})");
                    break;
                case BodyFieldKind.TextList:
                    w.Line($"if ({fi}.IsInvalid) {Fail(i)}");
                    assigns.Add(f.Nullable ? $"{Analysis.Identifier(f.Member)} = {fi}.IsMissing ? null : b.TextList({fi})" : $"{Analysis.Identifier(f.Member)} = b.TextList({fi})");
                    break;
                case BodyFieldKind.Nested:
                    if (f.Nullable)
                    {
                        w.Line($"if ({fi}.IsInvalid) {Fail(i, $"e{i}")}");
                        assigns.Add($"{Analysis.Identifier(f.Member)} = {fi}.IsMissing ? null : n{i}");
                    }
                    else
                    {
                        w.Line($"if ({fi}.Kind != {Http}.BodyKind.Nested) {Fail(i, $"e{i}")}");
                        assigns.Add($"{Analysis.Identifier(f.Member)} = n{i}");
                    }
                    break;
                default:
                    string get = f.Kind switch
                    {
                        BodyFieldKind.Int64 => $"{fi}.IntegerValue",
                        BodyFieldKind.Int32 => $"(int){fi}.IntegerValue",
                        BodyFieldKind.Double => $"{fi}.FloatValue",
                        _ => $"{fi}.BoolValue",
                    };
                    string? outside = Outside(f, f.Kind == BodyFieldKind.Double ? $"{fi}.FloatValue" : $"{fi}.IntegerValue");
                    if (f.Nullable)
                    {
                        w.Line(outside is null ? $"if ({fi}.IsInvalid) {Fail(i)}" : $"if ({fi}.IsInvalid || {fi}.IsValue && ({outside})) {Fail(i)}");
                        assigns.Add($"{Analysis.Identifier(f.Member)} = {fi}.IsMissing ? null : {get}");
                    }
                    else
                    {
                        w.Line(outside is null ? $"if (!{fi}.IsValue) {Fail(i)}" : $"if (!{fi}.IsValue || {outside}) {Fail(i)}");
                        assigns.Add($"{Analysis.Identifier(f.Member)} = {get}");
                    }
                    break;
            }
        }
        w.Line(assigns.Count == 0 ? "value = new();" : $"value = new() {{ {string.Join(", ", assigns)} }};");
    }

    /// <summary>The condition that <paramref name="value"/> is outside the field's [Range], or null when it has none.</summary>
    static string? Outside(BodyField f, string value)
    {
        string? low = f.Min is null ? null : $"{value} {(f.MinExclusive ? "<=" : "<")} {f.Min}";
        string? high = f.Max is null ? null : $"{value} {(f.MaxExclusive ? ">=" : ">")} {f.Max}";
        return low is null ? high : high is null ? low : $"{low} || {high}";
    }

    // ---- Literals ----

    static string Literal(string s)
    {
        var sb = new StringBuilder("\"");
        foreach (char c in s)
        {
            switch (c)
            {
                case '"': sb.Append("\\\""); break;
                case '\\': sb.Append("\\\\"); break;
                case '\n': sb.Append("\\n"); break;
                case '\r': sb.Append("\\r"); break;
                case '\t': sb.Append("\\t"); break;
                default:
                    if (c < ' ') sb.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                    else sb.Append(c);
                    break;
            }
        }
        return sb.Append('"').ToString();
    }

    static string Utf8Literal(string s) => Literal(s) + "u8";
