using System.Collections.Concurrent;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Operations;

namespace CodeFusion.Http.Generators;

/// <summary>
/// The rules that keep handlers at zero allocations: static handlers (CFH0001), no string parameters (CFH0002),
/// replies the generator can send (CFH0003), no Utf8 kept in a class (CFH0004), no LINQ in a handler (CFH0005).
/// </summary>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class HandlerAnalyzer : DiagnosticAnalyzer
{
    /// <summary>The diagnostic property that says a non-static lambda captures, so adding static won't fix it.</summary>
    public const string CapturesProperty = "Captures";

    // CFH0005 for a handler method: found once the whole compilation has been seen, so it carries the tag. The
    // same rule as the lambda's, so the same id.
#pragma warning disable RS1019
    static readonly DiagnosticDescriptor LinqInHandlerMethod = new(
        "CFH0005", Diagnostics.LinqInHandler.Title, Diagnostics.LinqInHandler.MessageFormat,
        Diagnostics.LinqInHandler.Category, DiagnosticSeverity.Error, true, Diagnostics.LinqInHandler.Description,
        customTags: WellKnownDiagnosticTags.CompilationEnd);
#pragma warning restore RS1019

    /// <inheritdoc/>
    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics { get; } =
        [Diagnostics.NotStatic, Diagnostics.StringParameter, Diagnostics.CannotSend, Diagnostics.Utf8InClass, Diagnostics.LinqInHandler, LinqInHandlerMethod];

    /// <inheritdoc/>
    public override void Initialize(AnalysisContext context)
    {
        if (context is null) throw new System.ArgumentNullException(nameof(context));
        // Files that look generated too (a *.g.cs, an <auto-generated> header): a Map call there is compiled all the
        // same, and the generator leaves these rules to this analyzer and skips the call, so the endpoint would be
        // lost without a word.
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.Analyze | GeneratedCodeAnalysisFlags.ReportDiagnostics);
        context.EnableConcurrentExecution();
        context.RegisterCompilationStartAction(start =>
        {
            if (KnownTypes.From(start.Compilation) is not { } known) return;
            INamedTypeSymbol?[] linq =
            [
                start.Compilation.GetTypeByMetadataName("System.Linq.Enumerable"),
                start.Compilation.GetTypeByMetadataName("System.Linq.Queryable"),
                start.Compilation.GetTypeByMetadataName("System.Linq.ParallelEnumerable"),
            ];
            var handlerMethods = new ConcurrentDictionary<IMethodSymbol, bool>(SymbolEqualityComparer.Default);
            var linqCalls = new ConcurrentBag<(ISymbol Method, Location At, string Name)>();

            start.RegisterOperationAction(op =>
            {
                var call = (IInvocationOperation)op.Operation;
                if (IsLinq(call.TargetMethod, linq))
                {
                    if (op.ContainingSymbol is IMethodSymbol m) linqCalls.Add((m, call.Syntax.GetLocation(), call.TargetMethod.Name));
                    return;
                }
                if (Analysis.Verb(call.TargetMethod, known) is null) return;
                AnalyzeMap(op, call, known, linq, handlerMethods);
            }, OperationKind.Invocation);

            var storage = new Storage(start.Compilation, known);
            start.RegisterSymbolAction(storage.Analyze, SymbolKind.Field, SymbolKind.Property, SymbolKind.NamedType);

            start.RegisterCompilationEndAction(end =>
            {
                foreach (var (method, at, name) in linqCalls)
                    if (handlerMethods.ContainsKey((IMethodSymbol)method.OriginalDefinition))
                        end.ReportDiagnostic(Diagnostic.Create(LinqInHandlerMethod, at, name));
            });
        });
    }

    static bool IsLinq(IMethodSymbol m, INamedTypeSymbol?[] linq)
    {
        INamedTypeSymbol t = (m.ReducedFrom ?? m).ContainingType;
        foreach (var l in linq)
            if (l is not null && SymbolEqualityComparer.Default.Equals(t, l)) return true;
        return false;
    }

    static void AnalyzeMap(OperationAnalysisContext op, IInvocationOperation call, KnownTypes known, INamedTypeSymbol?[] linq,
        ConcurrentDictionary<IMethodSymbol, bool> handlerMethods)
    {
        IArgumentOperation? handlerArg = call.Arguments.FirstOrDefault(a => a.Parameter?.Name == "handler");
        if (handlerArg is null) return;
        var (method, lambda, group) = Analysis.Handler(handlerArg.Value);
        if (method is null) return; // the generator reports it
        Location at = handlerArg.Syntax.GetLocation();

        if (lambda is not null)
        {
            if (!lambda.Symbol.IsStatic)
            {
                var captured = Captured(lambda);
                var props = ImmutableDictionary<string, string?>.Empty.Add(CapturesProperty, captured is null ? "false" : "true");
                string message = captured switch
                {
                    null => "Mark the handler lambda static: a lambda that starts capturing allocates a closure",
                    { Function: true } c => $"The handler lambda calls the local function '{c.Name}', which isn't static: make it static, then the lambda",
                    { } c => $"The handler lambda captures '{c.Name}', which allocates a closure: pass it as a service or a parameter and make the lambda static",
                };
                op.ReportDiagnostic(Diagnostic.Create(Diagnostics.NotStatic, LambdaStart(lambda) ?? at, props, message));
            }
            foreach (IOperation inner in lambda.Body.Descendants())
                if (inner is IInvocationOperation c && IsLinq(c.TargetMethod, linq))
                    op.ReportDiagnostic(Diagnostic.Create(Diagnostics.LinqInHandler, c.Syntax.GetLocation(), c.TargetMethod.Name));
        }
        else if (group is not null)
        {
            if (!method.IsStatic)
                op.ReportDiagnostic(Diagnostic.Create(Diagnostics.NotStatic, at,
                    $"The handler '{method.Name}' is an instance method: make it static, and pass what it uses as services or parameters"));
            handlerMethods.TryAdd(method.OriginalDefinition, true);
        }

        foreach (IParameterSymbol p in method.Parameters)
            if (p.Type.SpecialType == SpecialType.System_String)
            {
                Location pAt = lambda is not null && p.Locations.FirstOrDefault() is { IsInSource: true } l ? l : at;
                op.ReportDiagnostic(Diagnostic.Create(Diagnostics.StringParameter, pAt, p.Name));
            }

        var analysis = new Analysis(known);
        if (analysis.Reply(method.ReturnType, at, out string? why) is null && why is not null)
            op.ReportDiagnostic(Diagnostic.Create(Diagnostics.CannotSend, at, why));
    }

    /// <summary>What keeps the lambda from being static: the first variable from outside it that it uses (or "this"),
    /// itself or through a local function from outside; else such a local function that isn't static, which a static
    /// lambda can't call either. Null when nothing does.</summary>
    static (string Name, bool Function)? Captured(IAnonymousFunctionOperation lambda)
    {
        IOperation root = lambda;
        while (root.Parent is { } parent) root = parent;
        IMethodSymbol? function = null;
        string? variable = Captured(lambda.Body, lambda.Symbol, root, new HashSet<IMethodSymbol>(SymbolEqualityComparer.Default), ref function);
        return variable is not null ? (variable, false) : function is not null ? (function.Name, true) : null;
    }

    static string? Captured(IOperation body, IMethodSymbol self, IOperation root, HashSet<IMethodSymbol> seen, ref IMethodSymbol? function)
    {
        foreach (IOperation o in body.Descendants())
        {
            switch (o)
            {
                case IInstanceReferenceOperation { ReferenceKind: InstanceReferenceKind.ContainingTypeInstance }:
                    return "this";
                case ILocalReferenceOperation l when !Inside(l.Local, self):
                    return l.Local.Name;
                case IParameterReferenceOperation p when !Inside(p.Parameter, self):
                    return p.Parameter.Name;
            }
            IMethodSymbol? called = o switch
            {
                IInvocationOperation i => i.TargetMethod,
                IMethodReferenceOperation r => r.Method,
                _ => null,
            };
            if (called is not { MethodKind: MethodKind.LocalFunction, IsStatic: false } || Inside(called, self) || !seen.Add(called.OriginalDefinition)) continue;
            function ??= called;
            foreach (IOperation d in root.Descendants())
                if (d is ILocalFunctionOperation f && SymbolEqualityComparer.Default.Equals(f.Symbol, called.OriginalDefinition)
                    && (f.Body ?? f.IgnoredBody) is { } fBody && Captured(fBody, f.Symbol, root, seen, ref function) is { } through)
                    return through;
        }
        return null;
    }

    /// <summary>Whether <paramref name="s"/> is declared in <paramref name="lambda"/> or a function inside it.</summary>
    static bool Inside(ISymbol s, IMethodSymbol lambda)
    {
        for (ISymbol? c = s.ContainingSymbol; c is not null; c = c.ContainingSymbol)
        {
            if (SymbolEqualityComparer.Default.Equals(c, lambda)) return true;
            if (c is not IMethodSymbol { MethodKind: MethodKind.AnonymousFunction or MethodKind.LocalFunction }) return false;
        }
        return false;
    }

    static Location? LambdaStart(IAnonymousFunctionOperation lambda) => lambda.Syntax switch
    {
        ParenthesizedLambdaExpressionSyntax p => Location.Create(p.SyntaxTree, Microsoft.CodeAnalysis.Text.TextSpan.FromBounds(p.SpanStart, p.ArrowToken.Span.End)),
        SimpleLambdaExpressionSyntax s => Location.Create(s.SyntaxTree, Microsoft.CodeAnalysis.Text.TextSpan.FromBounds(s.SpanStart, s.ArrowToken.Span.End)),
        AnonymousMethodExpressionSyntax a => Location.Create(a.SyntaxTree, a.DelegateKeyword.Span),
        _ => null,
    };

    /// <summary>
    /// CFH0004 in one compilation: a field, an auto-property's storage, or a primary-constructor parameter a member
    /// keeps, of a class, or a static one of a struct, that holds a Utf8 or another view. A CodeFusion.Data entity's
    /// instance members are exempt: it describes a table to the query generator and is never built. A class that
    /// derives from an entity (or an entity's base) without being one is reported for what it inherits. The endpoint
    /// generator's own output is exempt: its endpoints hold their handler, a static lambda, as a Func.
    /// </summary>
    sealed class Storage(Compilation compilation, KnownTypes known)
    {
        readonly System.Lazy<HashSet<ITypeSymbol>> _entities = new(() => Entities(compilation, known));
        readonly ConcurrentDictionary<INamedTypeSymbol, ImmutableArray<IParameterSymbol>> _kept = new(SymbolEqualityComparer.Default);

        public void Analyze(SymbolAnalysisContext s)
        {
            ISymbol member = s.Symbol;
            if (member.IsImplicitlyDeclared) return;
            if (member is INamedTypeSymbol type)
            {
                if (type.TypeKind != TypeKind.Class || Generated(type) || Entity(type)) return;
                foreach (IParameterSymbol p in Kept(type))
                    if (Transient(p.Type) is { } held) Report(s, type, p, p.Locations, held);
                // what it inherits from an entity is a column there and storage here (a class further down inherits it
                // through this one, which says so)
                for (INamedTypeSymbol? b = type.BaseType; b is not null && Entity(b); b = b.BaseType)
                {
                    foreach (ISymbol m in b.GetMembers())
                        if (!m.IsStatic && Stored(m, b) is { } t && Transient(t) is { } held) Report(s, type, m, type.Locations, held);
                    foreach (IParameterSymbol p in Kept(b))
                        if (Transient(p.Type) is { } held) Report(s, type, p, type.Locations, held);
                }
                return;
            }
            // a struct's instance members are held, and checked, wherever the struct is
            if (member.ContainingType is not { } owner || Generated(owner)
                || (owner.TypeKind == TypeKind.Class ? !member.IsStatic && Entity(owner) : owner.TypeKind != TypeKind.Struct || !member.IsStatic))
                return;
            if (Stored(member, owner) is { } stored && Transient(stored) is { } found) Report(s, owner, member, member.Locations, found);
        }

        /// <summary>The type a field or an auto-property stores; null for anything else.</summary>
        static ITypeSymbol? Stored(ISymbol member, INamedTypeSymbol owner) => member switch
        {
            IFieldSymbol { IsImplicitlyDeclared: false } f => f.Type,
            IPropertySymbol p when owner.GetMembers().OfType<IFieldSymbol>().Any(f => SymbolEqualityComparer.Default.Equals(f.AssociatedSymbol, p)) => p.Type,
            _ => null,
        };

        static void Report(SymbolAnalysisContext s, INamedTypeSymbol owner, ISymbol member, ImmutableArray<Location> at, string held)
        {
            foreach (Location l in at)
                if (l.IsInSource) s.ReportDiagnostic(Diagnostic.Create(Diagnostics.Utf8InClass, l, $"{owner.Name}.{member.Name}", held));
        }

        bool Entity(INamedTypeSymbol type) => _entities.Value.Contains(type.OriginalDefinition);

        static bool Generated(INamedTypeSymbol owner) => owner.ContainingNamespace?.ToDisplayString() == "CodeFusion.Http.Generated";

        string? Transient(ITypeSymbol t) =>
            Transient(t, false, new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default), new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default));

        /// <summary>
        /// The name of the view type a value of <paramref name="t"/> can hold and hand back: itself, or in a struct's
        /// fields and kept parameters, an array or a type argument; null when it holds none. A type parameter declared
        /// <c>in</c> only takes values, so a <c>Func&lt;Utf8, bool&gt;</c> or an <c>IEqualityComparer&lt;Utf8&gt;</c>
        /// can't hand one back (<paramref name="inputOnly"/>), and one inside it flips back (an
        /// <c>Action&lt;Action&lt;Utf8&gt;&gt;</c> calls back with one). A type parameter with no variance goes both ways.
        /// </summary>
        string? Transient(ITypeSymbol t, bool inputOnly, HashSet<ITypeSymbol> seenOut, HashSet<ITypeSymbol> seenIn)
        {
            if (!(inputOnly ? seenIn : seenOut).Add(t)) return null;
            if (known.IsTransient(t)) return inputOnly ? null : t.Name;
            switch (t)
            {
                case IArrayTypeSymbol a:
                    return Transient(a.ElementType, false, seenOut, seenIn);
                case INamedTypeSymbol n:
                    for (int i = 0; i < n.TypeArguments.Length; i++)
                    {
                        bool input = n.TypeParameters[i].Variance switch
                        {
                            VarianceKind.In => !inputOnly,
                            VarianceKind.Out => inputOnly,
                            _ => false,
                        };
                        if (Transient(n.TypeArguments[i], input, seenOut, seenIn) is { } x) return x;
                    }
                    if (n.TypeKind == TypeKind.Struct && n.SpecialType == SpecialType.None)
                    {
                        foreach (IFieldSymbol f in n.GetMembers().OfType<IFieldSymbol>())
                            if (!f.IsStatic && Transient(f.Type, inputOnly, seenOut, seenIn) is { } x) return x;
                        foreach (IParameterSymbol p in Kept(n))
                            if (Transient(p.Type, inputOnly, seenOut, seenIn) is { } x) return x;
                    }
                    return null;
                default:
                    return null;
            }
        }

        /// <summary>The primary-constructor parameters of <paramref name="type"/> its members use, which the compiler
        /// keeps in hidden fields no symbol shows. One read only by initializers and the base call isn't kept; one a
        /// lambda or a local function uses is, as they may run later.</summary>
        ImmutableArray<IParameterSymbol> Kept(INamedTypeSymbol type) => _kept.GetOrAdd(type.OriginalDefinition, t =>
        {
            IMethodSymbol? primary = t.InstanceConstructors.FirstOrDefault(c => c.DeclaringSyntaxReferences.Any(r => r.GetSyntax() is TypeDeclarationSyntax));
            if (primary is null || primary.Parameters.IsEmpty || !t.DeclaringSyntaxReferences.Any()) return [];
            var kept = new HashSet<IParameterSymbol>(SymbolEqualityComparer.Default);
            foreach (SyntaxReference r in t.DeclaringSyntaxReferences)
            {
                SemanticModel? model = null;
                foreach (IdentifierNameSyntax id in r.GetSyntax().DescendantNodes().OfType<IdentifierNameSyntax>())
                {
                    if (!primary.Parameters.Any(p => p.Name == id.Identifier.ValueText)) continue;
                    // RS1030: symbol actions get no semantic model, and only a type with a primary constructor that
                    // names one of its parameters gets here
#pragma warning disable RS1030
                    model ??= compilation.GetSemanticModel(id.SyntaxTree);
#pragma warning restore RS1030
                    if (model.GetSymbolInfo(id).Symbol is not IParameterSymbol p || !SymbolEqualityComparer.Default.Equals(p.ContainingSymbol, primary)
                        || id.Ancestors().Any(a => a is InvocationExpressionSyntax { Expression: IdentifierNameSyntax { Identifier.ValueText: "nameof" } } n && model.GetOperation(n) is INameOfOperation))
                        continue;
                    ISymbol? at = model.GetEnclosingSymbol(id.SpanStart);
                    if (at is not (IFieldSymbol or IPropertySymbol) && !SymbolEqualityComparer.Default.Equals(at, primary)) kept.Add(p);
                }
            }
            return [.. kept];
        });

        /// <summary>The entities: the classes a data context in this compilation has a <c>Table&lt;T&gt;</c> for (its
        /// own or a base context's, which may be in a library), and their base classes, which hold their columns too.
        /// In an assembly that references CodeFusion.Data and has no context (its entities' context is elsewhere),
        /// the classes marked with EF's <c>[Table]</c>. Known by name: CodeFusion.Http doesn't reference
        /// CodeFusion.Data.</summary>
        static HashSet<ITypeSymbol> Entities(Compilation c, KnownTypes known)
        {
            INamedTypeSymbol? table = c.GetTypeByMetadataName("CodeFusion.Data.Table`1"), context = c.GetTypeByMetadataName("CodeFusion.Data.DataContext");
            var entities = new List<INamedTypeSymbol>();
            var marked = new List<INamedTypeSymbol>();
            bool contexts = false;
            var pending = new Stack<INamespaceOrTypeSymbol>();
            pending.Push(c.Assembly.GlobalNamespace);
            while (pending.Count > 0)
            {
                foreach (ISymbol m in pending.Pop().GetMembers())
                {
                    if (m is INamespaceOrTypeSymbol nt) pending.Push(nt);
                    if (m is not INamedTypeSymbol { TypeKind: TypeKind.Class } type) continue;
                    if (known.Table is not null && type.GetAttributes().Any(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, known.Table))) marked.Add(type);
                    if (table is null || context is null || !DerivesFrom(type, context)) continue;
                    contexts = true;
                    for (INamedTypeSymbol? b = type; b is not null && !SymbolEqualityComparer.Default.Equals(b.OriginalDefinition, context); b = b.BaseType)
                        foreach (IPropertySymbol p in b.GetMembers().OfType<IPropertySymbol>())
                            if (p.Type is INamedTypeSymbol { TypeArguments.Length: 1 } t && SymbolEqualityComparer.Default.Equals(t.OriginalDefinition, table)
                                && t.TypeArguments[0] is INamedTypeSymbol entity)
                                entities.Add(entity);
                }
            }
            if (context is not null && !contexts) entities.AddRange(marked);
            var found = new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default);
            foreach (INamedTypeSymbol e in entities)
                for (INamedTypeSymbol? b = e; b is not null && b.SpecialType != SpecialType.System_Object; b = b.BaseType)
                    found.Add(b.OriginalDefinition);
            return found;
        }

        static bool DerivesFrom(INamedTypeSymbol type, INamedTypeSymbol baseType)
        {
            for (INamedTypeSymbol? b = type.BaseType; b is not null; b = b.BaseType)
                if (SymbolEqualityComparer.Default.Equals(b.OriginalDefinition, baseType)) return true;
            return false;
        }
    }
}
